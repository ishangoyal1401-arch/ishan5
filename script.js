function setCity(city) {

    if (!data[city]) return;

    currentCity = city;

    localStorage.setItem(
        "taskmate-city",
        city
    );

    currentQuery = "";

    $("searchInput").value = "";

    $("locationMenu")
        .classList
        .remove("open");

    render();

    toast(
        `Showing professionals in ${city}`
    );

}


function performSearch() {

    currentQuery =
        $("searchInput").value;

    render();

    $("pros").scrollIntoView({
        behavior: "smooth"
    });

}


function book(index) {

    const pro =
        data[currentCity].pros[index];

    activePro = pro;


    $("bookingName").textContent =
        pro[0];

    $("bookingRole").textContent =
        pro[1];

    $("bookingPrice").textContent =
        pro[4];


    $("bookingContent")
        .classList
        .remove("hidden");

    $("bookingSuccess")
        .classList
        .add("hidden");


    openModal(
        "bookingModal"
    );

}


/* ================= CLICK HANDLERS ================= */


document.addEventListener(
    "click",
    event => {

        const bookButton =
            event.target.closest(
                "[data-pro-index]"
            );


        if (bookButton) {

            book(
                Number(
                    bookButton.dataset.proIndex
                )
            );

        }


        const category =
            event.target.closest(
                "[data-search]"
            );


        if (category) {

            currentQuery =
                category.dataset.search;

            $("searchInput").value =
                currentQuery;

            render();

            $("pros").scrollIntoView({
                behavior: "smooth"
            });

        }

    }
);


